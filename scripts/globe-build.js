// Builds routes/admin/public/globedata.js: the land the Flights Passport globe draws, as lon/lat rings.
// Source: Natural Earth 110m land (public domain, https://www.naturalearthdata.com/), fetched once by hand:
//   curl -sL -o /tmp/land.geojson https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
//   node scripts/globe-build.js /tmp/land.geojson > routes/admin/public/globedata.js
// Every ring is simplified (Ramer-Douglas-Peucker, 0.25 degree tolerance), rounded to half a degree and written as one string
// of comma-separated integers in half-degree units: the first point absolute (lon, lat), then deltas. Polygons that lie
// entirely south of 60 S (Antarctica) are left out. The flat map's worldmap.js is built separately and is not touched.
const fs = require('fs');

const TOL = 0.25;
const geo = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));

function rdp(pts, tol) {
    if (pts.length < 3) return pts;
    const keep = new Uint8Array(pts.length);
    keep[0] = 1;
    keep[pts.length - 1] = 1;
    const stack = [[0, pts.length - 1]];
    while (stack.length) {
        const [i, j] = stack.pop();
        const [ax, ay] = pts[i];
        const [bx, by] = pts[j];
        const dx = bx - ax;
        const dy = by - ay;
        const len = Math.hypot(dx, dy);
        let best = -1;
        let at = -1;
        for (let k = i + 1; k < j; k++) {
            const [px, py] = pts[k];
            const d = len ? Math.abs(dy * px - dx * py + bx * ay - by * ax) / len : Math.hypot(px - ax, py - ay);
            if (d > best) { best = d; at = k; }
        }
        if (best > tol) { keep[at] = 1; stack.push([i, at], [at, j]); }
    }
    return pts.filter((_, k) => keep[k]);
}

// A closed ring: split it at its two most distant-from-each-other points so RDP keeps the shape.
function simplifyRing(ring) {
    const open = ring.slice(0, -1);
    if (open.length < 4) return open;
    let far = 0;
    let fd = -1;
    for (let k = 1; k < open.length; k++) {
        const d = Math.hypot(open[k][0] - open[0][0], open[k][1] - open[0][1]);
        if (d > fd) { fd = d; far = k; }
    }
    const a = rdp(open.slice(0, far + 1), TOL);
    const b = rdp(open.slice(far).concat([open[0]]), TOL);
    return a.concat(b.slice(1, -1));
}

const out = [];
let points = 0;
for (const f of geo.features) {
    const g = f.geometry;
    const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
    for (const poly of polys) {
        if (poly[0].every(([, lat]) => lat < -60)) continue;
        for (const ring of poly) {
            const pts = simplifyRing(ring).map(([lon, lat]) => [Math.round(lon * 2), Math.round(lat * 2)]);
            const dedup = pts.filter((p, k) => k === 0 || p[0] !== pts[k - 1][0] || p[1] !== pts[k - 1][1]);
            if (dedup.length < 3) continue;
            const nums = [];
            dedup.forEach(([x, y], k) => {
                if (k === 0) nums.push(x, y);
                else nums.push(x - dedup[k - 1][0], y - dedup[k - 1][1]);
            });
            points += dedup.length;
            out.push(nums.join(','));
        }
    }
}

process.stdout.write(`// Generated by scripts/globe-build.js from Natural Earth 110m land (public domain). Do not edit.
// ${out.length} rings, ${points} points. Each string: half-degree integers, first point (lon, lat) absolute, then deltas.
export const GLOBE_LAND = [
${out.map((s) => `'${s}'`).join(',\n')},
];

// The rings as arrays of [lon, lat] in degrees.
export function landRings() {
    return GLOBE_LAND.map((s) => {
        const n = s.split(',').map(Number);
        const ring = [];
        let x = 0;
        let y = 0;
        for (let k = 0; k < n.length; k += 2) {
            x += n[k];
            y += n[k + 1];
            ring.push([x / 2, y / 2]);
        }
        return ring;
    });
}
`);
