// Builds routes/admin/public/worldmap.js: the land outline the Flights Passport map draws, as one SVG path.
// Source: Natural Earth 110m land (public domain, https://www.naturalearthdata.com/), fetched once by hand:
//   curl -sL -o land.geojson https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
//   node scripts/worldmap-build.js land.geojson > routes/admin/public/worldmap.js
// Equirectangular: x = longitude + 180, y = 90 - latitude (a 360 x 180 box). Coordinates are rounded to a tenth of
// a degree and written as relative moves, so the path stays near 20 KB. Polygons south of 60 S are left out.
const fs = require('fs');

const geo = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const rings = [];
for (const f of geo.features) {
    const g = f.geometry;
    const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
    for (const poly of polys) {
        if (poly[0].every(([, lat]) => lat < -60)) continue;
        for (const ring of poly) rings.push(ring);
    }
}

const r1 = (n) => Math.round(n * 10) / 10;
const num = (n) => String(r1(n)).replace(/^(-?)0\./, '$1.');
let d = '';
for (const ring of rings) {
    let px = 0;
    let py = 0;
    const pts = ring.map(([lon, lat]) => [r1(lon + 180), r1(90 - lat)]);
    const out = [];
    pts.forEach(([x, y], i) => {
        if (i === 0) out.push(`M${num(x)} ${num(y)}`);
        else {
            const dx = r1(x - px);
            const dy = r1(y - py);
            if (dx !== 0 || dy !== 0) out.push(`l${num(dx)} ${num(dy)}`);
        }
        px = x;
        py = y;
    });
    d += `${out.join('')}z`;
}

process.stdout.write(`// Generated by scripts/worldmap-build.js from Natural Earth 110m land (public domain). Do not edit.
// One path in a 360 x 180 box: x = longitude + 180, y = 90 - latitude.
export const LAND = '${d}';
`);
