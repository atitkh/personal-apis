await check('overview: dragging a node pulls its neighbours along, nothing is selected or saved, and it settles again', async () => {
    await openOverview(); await settled();
    const hubBefore = await pos(hubKey);
    const near = await page.evaluate((hk) => {
        const key = hk.match(/node:(.*)"/)[1];
        return fetch('/admin/api/graph/overview', { headers: { 'X-Requested-With': 'hub-admin' } }).then((r) => r.json()).then((ov) => ov.edges.filter((e) => e.from === key || e.to === key).map((e) => (e.from === key ? e.to : e.from)).slice(0, 6));
    }, hubKey);
    ok(near.length >= 4, 'hub has neighbours');
    const sels = near.map((k) => `[data-key="node:${k}"]`);
    const before = [];
    for (const s of sels) before.push(await pos(s));
    const c = await centerOf(hubKey);
    await page.mouse.move(c.x, c.y); await page.mouse.down();
    await page.mouse.move(c.x + 140, c.y + 80, { steps: 8 });
    await page.waitForTimeout(900);
    const awake = await page.locator('svg.graph-svg[data-sim="awake"]').count();
    const hubMid = await pos(hubKey);
    let moved = 0;
    for (let i = 0; i < sels.length; i += 1) { const a = await pos(sels[i]); moved += Math.hypot(a.x - before[i].x, a.y - before[i].y); }
    await page.mouse.up();
    ok(Math.hypot(hubMid.x - hubBefore.x, hubMid.y - hubBefore.y) > 30, 'the dragged node moved');
    ok(awake === 1, 'the simulation is awake while dragging');
    ok(moved / sels.length > 20, `neighbours followed: mean move ${(moved / sels.length).toFixed(1)}`);
    ok(await page.locator('[data-key="graph-card"]').isHidden(), 'drag did not select');
    await asleep('after the drop the simulation');
    await page.reload(); await page.waitForSelector('svg.graph-svg[data-ready="1"] .graph-node'); await asleep();
    const again = await pos(hubKey);
    ok(Math.hypot(again.x - hubBefore.x, again.y - hubBefore.y) < 1, 'a reload puts it back');
});
