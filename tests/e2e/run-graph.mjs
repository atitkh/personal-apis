await check('simulation of 400 records: steps are cheap and frames stay smooth', async () => {
    const out = await page.evaluate(async () => {
        const m = await import(new URL('views/graphCanvas.js', location.href.replace(/#.*$/, '')).href);
        const doms = ['entities', 'trips', 'places', 'deadlines', 'flights'];
        const make = () => { const nodes = Array.from({ length: 400 }, (_, i) => ({ key: `${doms[i % 5]}:${i}`, domain: doms[i % 5], title: `Record ${i}`, degree: 1 + (i % 7) })); const edges = nodes.slice(1).map((n, i) => ({ from: nodes[Math.floor(i / 3)].key, to: n.key, rel: 'x' })); return { nodes, edges }; };
        const a = make(); const anc = m.seedOverview(a.nodes); const sim = m.createSim(a.nodes, a.edges, anc, m.DEFAULTS);
        const t0 = performance.now(); for (let i = 0; i < 40; i += 1) sim.step(); const stepMs = (performance.now() - t0) / 40;
        const b = make(); const sim2 = m.createSim(b.nodes, b.edges, m.seedOverview(b.nodes), m.DEFAULTS); for (let i = 0; i < 40; i += 1) sim2.step();
        const same = a.nodes.every((n, i) => n.x === b.nodes[i].x && n.y === b.nodes[i].y); const finite = a.nodes.every((n) => Number.isFinite(n.x) && Number.isFinite(n.y));
        const frames = async (until) => { const g = []; let pv = performance.now(); await new Promise((res) => { const t = (now) => { g.push(now - pv); pv = now; if (g.length > 40 || now > until) res(); else requestAnimationFrame(t); }; requestAnimationFrame(t); }); return g.slice(5).sort((x, y) => x - y); };
        const base = await frames(performance.now() + 3000);
        const c = make(); const anc3 = m.seedOverview(c.nodes);
        const holder = document.createElement('div'); holder.style.cssText = 'position:fixed;left:0;top:0;width:1100px;height:700px;z-index:999'; document.body.append(holder);
        const canvas = m.createCanvas({ nodes: c.nodes, edges: c.edges, anchors: anc3, centerKey: null, selected: null, hidden: new Set(), oneLabel: (d) => d, dense: true, label: 'x', onSelect() {}, onFocus() {} });
        holder.append(canvas.el); canvas.el.style.height = '700px';
        const gaps = []; let prev = performance.now(); const until = prev + 9000;
        await new Promise((res) => { const tick = (now) => { gaps.push(now - prev); prev = now; if (now > until || (canvas.el.querySelector('svg').dataset.sim === 'asleep' && gaps.length > 30)) res(); else requestAnimationFrame(tick); }; requestAnimationFrame(tick); });
        const slow = canvas.el.querySelector('svg').dataset.stepMs; const avg = canvas.el.querySelector('svg').dataset.avgMs; const g = gaps.slice(5).sort((x, y) => x - y);
        canvas.destroy(); holder.remove();
        return { stepMs, same, finite, base95: base[Math.floor(base.length * 0.95)], frames: g.length, p50: g[Math.floor(g.length * 0.5)], p95: g[Math.floor(g.length * 0.95)], max: g[g.length - 1], slow: Number(slow), avg: Number(avg) };
    });
    console.log(`400 nodes: (idle page p95 ${out.base95.toFixed(1)} ms) ${out.stepMs.toFixed(1)} ms per sim step, ${out.frames} frames, p50 ${out.p50.toFixed(1)} ms, p95 ${out.p95.toFixed(1)} ms, max ${out.max.toFixed(1)} ms, slowest step+paint ${out.slow} ms, average script time per frame ${out.avg} ms`);
    ok(out.finite && out.same, `finite and repeatable: ${JSON.stringify(out)}`);
    ok(out.stepMs < 12, `a step took ${out.stepMs.toFixed(1)} ms`);
    ok(out.avg < 8, `script time per frame ${out.avg} ms`);
    ok(out.p50 < 40, `median frame ${out.p50.toFixed(1)} ms (idle page p95 ${out.base95.toFixed(1)})`);
});
